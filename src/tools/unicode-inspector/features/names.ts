// A compact Unicode character name table for the most common blocks. Names for accented Latin
// letters are derived from their canonical decomposition (base letter + one combining mark);
// CJK ideographs, Hangul syllables, variation selectors, tags and regional indicators are
// algorithmic. Anything else falls back to its block and general category in the UI.

/** Sequential names from a start code point ('' = no name listed). */
function seq(start: number, names: string, prefix = ''): [number, string][] {
  return names.split('|').flatMap((n, i) => (n ? [[start + i, prefix + n] as [number, string]] : []));
}

