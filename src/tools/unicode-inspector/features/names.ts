const FITZPATRICK = ['1-2', '3', '4', '5', '6'];
const UNIFIED_IDEOGRAPH = /^\p{Unified_Ideograph}$/u;

const hex = (cp: number) => cp.toString(16).toUpperCase().padStart(4, '0');

function isLatinLetterBlock(cp: number) {
  return (cp >= 0xc0 && cp <= 0x24f) || (cp >= 0x1e00 && cp <= 0x1eff);
}

/** The character's Unicode name if this table knows it, else null. */
export function charName(cp: number): string | null {
  const direct = TABLE.get(cp);
  if (direct) return direct;
  if (cp >= 0x41 && cp <= 0x5a) return `LATIN CAPITAL LETTER ${String.fromCharCode(cp)}`;
  if (cp >= 0x61 && cp <= 0x7a) return `LATIN SMALL LETTER ${String.fromCharCode(cp - 32)}`;
  if (cp >= 0x80 && cp <= 0x9f) return '<control>';
  if (cp >= 0xfe00 && cp <= 0xfe0f) return `VARIATION SELECTOR-${cp - 0xfe00 + 1}`;
  if (cp >= 0xe0100 && cp <= 0xe01ef) return `VARIATION SELECTOR-${cp - 0xe0100 + 17}`;
  if (cp === 0xe0001) return 'LANGUAGE TAG';
  if (cp === 0xe007f) return 'CANCEL TAG';
  if (cp >= 0xe0020 && cp <= 0xe007e) return `TAG ${charName(cp - 0xe0000)}`;
  if (cp >= 0x1f3fb && cp <= 0x1f3ff) return `EMOJI MODIFIER FITZPATRICK TYPE-${FITZPATRICK[cp - 0x1f3fb]}`;
  if (cp >= 0x1f1e6 && cp <= 0x1f1ff) return `REGIONAL INDICATOR SYMBOL LETTER ${String.fromCharCode(0x41 + cp - 0x1f1e6)}`;
  if (cp >= 0xff01 && cp <= 0xff5e) return `FULLWIDTH ${charName(cp - 0xfee0)}`;
  if (cp >= 0xac00 && cp <= 0xd7a3) {
    const s = cp - 0xac00;
    return `HANGUL SYLLABLE ${HANGUL_L[Math.floor(s / 588)]}${HANGUL_V[Math.floor((s % 588) / 28)]}${HANGUL_T[s % 28]}`;
  }
  const ch = String.fromCodePoint(cp);
  if (UNIFIED_IDEOGRAPH.test(ch)) return `CJK UNIFIED IDEOGRAPH-${hex(cp)}`;
  // Accented Latin letters: base letter + exactly one combining mark.
  if (isLatinLetterBlock(cp) && ch.normalize('NFC') === ch) {
    const parts = [...ch.normalize('NFD')].map((c) => c.codePointAt(0)!);
    if (parts.length === 2 && MARK_IN_NAME[parts[1]]) {
      const base = charName(parts[0]);
      if (base && /^LATIN (CAPITAL|SMALL) LETTER /.test(base) && !base.includes(' WITH ')) return `${base} WITH ${MARK_IN_NAME[parts[1]]}`;
    }
  }
  return null;
}

